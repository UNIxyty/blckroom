export const messages: Record<Lang, Record<MessageKey, string>> = { en, ru };

export function t(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let s: string = messages[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** stored user choice → Telegram client language → English. */
export function resolveLang(
  stored: string | null | undefined,
  telegramCode?: string | null,
): Lang {
  if (stored === "en" || stored === "ru") return stored;
  return telegramCode?.toLowerCase().startsWith("ru") ? "ru" : "en";
}
